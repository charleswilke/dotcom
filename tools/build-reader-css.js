// Derive the standalone reader's shared styles from the canonical stylesheet.
// This is a conservative selector subset, not viewport/coverage-based purging:
// keep global rules, pseudo states, responsive variants, fonts and animations.
const fs = require('node:fs');
const path = require('node:path');
const postcss = require('postcss');

function buildReaderCss(root = path.resolve(__dirname, '..')) {
    const sources = ['lib/article-archive.js', 'nav.js', 'common.js', 'article-archive.js', 'article-reader-ui.js', 'articles/archive.json', 'articles/local.json'];
    const vocabulary = new Set(sources.flatMap(file => fs.readFileSync(path.join(root, file), 'utf8').match(/[A-Za-z_][\w-]*/g) || []));
    function relevant(selector) {
        // Always retain the reader's own families, including new descendants
        // in posts that have not entered the permanent archive yet.
        if (/[.#](?:article-|scope-|nav-|byline-|transcript-)/.test(selector)) return true;
        // Attribute values and functional pseudo-classes aren't required classes:
        // :not(.missing) can match; :is(.a,.b) only needs one branch to match.
        // Ignore their contents conservatively instead of deleting valid rules.
        if (selector.includes('\\')) return true;
        let outer = '', depth = 0, bracket = 0, quote = '';
        for (const char of selector) {
            if (quote) { if (char === quote) quote = ''; continue; }
            if (char === '"' || char === "'") { quote = char; continue; }
            if (char === '[') bracket++;
            if (char === ']') { bracket--; continue; }
            if (bracket) continue;
            if (char === '(') depth++;
            if (char === ')') { depth--; continue; }
            if (!depth) outer += char;
        }
        return [...outer.matchAll(/[.#]([A-Za-z_][\w-]*)/g)].every(([,name]) =>
            /^(?:article-|scope-|nav-|byline-|transcript-)/.test(name) || vocabulary.has(name));
    }
    const css = postcss.parse(fs.readFileSync(path.join(root, 'styles.css'), 'utf8'));
    css.walkComments(comment => comment.remove());
    css.walkRules(rule => {
        if (rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
        const selectors = rule.selectors.filter(relevant);
        if (!selectors.length) rule.remove();
        else rule.selectors = selectors;
    });
    // Empty responsive/support wrappers are harmless but need not be shipped.
    css.walkAtRules(rule => { if (rule.nodes && !rule.nodes.length) rule.remove(); });
    const output = '/* Generated by tools/build-reader-css.js from styles.css. */\n' + css.toString() + '\n';
    fs.writeFileSync(path.join(root, 'reader-base.css'), output);
    return output;
}
if (require.main === module) buildReaderCss();
module.exports = { buildReaderCss };
